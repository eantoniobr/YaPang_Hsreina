// 0xce6b10: the table's static initializer. The motions each type does not
// use stay zero (the JP memsets each type's tail).
static int InitJpMotionTable() {
	memset(g_jpMotionTable, 0, sizeof(g_jpMotionTable));
	for (int type = 0; type < JP_MOTION_TYPE_COUNT; ++type) {
		for (int i = 0; i < JP_MOTION_COUNT; ++i) {
			const sJpMotionSource& source = s_jpMotionSources[type][i];
			sJpMotionText& motion = g_jpMotionTable[type][i];
			motion.m_name = source.m_name;
			for (int k = 0; k < 7; ++k) {
				const char* word = source.m_words[k];
				if (word != NULL && (source.m_translated & (1 << k)) != 0) {
					word = Jp_LookupText(word);
				}
				motion.m_command[k] = word;
			}
		}
	}
	return 0;
}

static int s_jpMotionTableInit = InitJpMotionTable();
